def gcd(x, y):
    while y:
        x, y = y, x % y
    return x


def belongs(target, generators):
    reachable = [False] * (target + 1)
    reachable[0] = True
    for n in range(1, target + 1):
        reachable[n] = any(
            n >= g and reachable[n - g] for g in generators
        )
    return reachable[target]


def main():
    witness = (9, 10, 12, 13)
    m, a, b, d = witness
    generators = witness

    def reject(reason):
        print("REFUTATION REJECTED:", reason)

    if not all(type(g) is int for g in generators):
        reject("the witness does not consist of four integers")
        return
    if not (4 <= m < a < b < d):
        reject("the ordering hypothesis fails")
        return

    common_divisor = 0
    for g in generators:
        common_divisor = gcd(common_divisor, g)
    if common_divisor != 1:
        reject("gcd(m,a,b,d) is not 1")
        return
    if a + b != m + d:
        reject("a+b=m+d fails")
        return

    for i, g in enumerate(generators):
        others = generators[:i] + generators[i + 1:]
        if belongs(g, others):
            reject(f"{g} is generated by the other three generators")
            return

    # Compute membership literally by nonnegative sums. The first run
    # of m consecutive members determines the conductor: adding m
    # proves that every subsequent integer is also a member.
    membership = []
    consecutive = 0
    n = 0
    while True:
        member = n == 0 or any(
            n >= g and membership[n - g] for g in generators
        )
        membership.append(member)
        consecutive = consecutive + 1 if member else 0
        if consecutive == m:
            c = n - m + 1
            break
        n += 1

    # Every Apéry element is below c+m, since s >= c+m implies s-m in S.
    while len(membership) < c + m:
        n = len(membership)
        membership.append(any(
            n >= g and membership[n - g] for g in generators
        ))

    L = [s for s in range(c) if membership[s]]
    A = [
        s for s in range(c + m)
        if membership[s] and (s < m or not membership[s - m])
    ]

    # Count elements having at least two distinct triples, not pairs.
    q = 0
    for w in A:
        triples = []
        for x in range(w // a + 1):
            for y in range((w - x * a) // b + 1):
                remainder = w - x * a - y * b
                for z in range(remainder // d + 1):
                    if x * a + y * b + z * d == w:
                        triples.append((x, y, z))
        if len(triples) >= 2:
            q += 1

    left = 4 * len(L) - c
    right = m - 4 + q
    if left < right:
        print(
            "REFUTATION CONFIRMED:",
            witness,
            f"4|L|-c={left}",
            f"m-4+q={right}",
        )
    else:
        reject(f"the conclusion holds: 4|L|-c={left}, m-4+q={right}")


if __name__ == "__main__":
    main()